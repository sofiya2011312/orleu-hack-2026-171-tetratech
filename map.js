async function buildSelectedRoute() {

    const info = document.getElementById("routeInfo");

    if (selectedRoutePlaces.length < 2) {

        info.textContent =
            "Выберите минимум две достопримечательности.";

        return;

    }

    if (selectedRoutePlaces.length > 10) {

        info.textContent =
            "Слишком много точек для построения маршрута.";

        return;

    }

    info.textContent = "Строим маршрут...";

    const coordinates = selectedRoutePlaces
        .map(place => `${place.lon},${place.lat}`)
        .join(";");

    const url =
        `https://router.project-osrm.org/route/v1/driving/${coordinates}?overview=full&geometries=geojson&steps=false`;

    try {

        const response = await fetch(url);

        if (!response.ok) {
            throw new Error("Маршрут недоступен");
        }

        const data = await response.json();

        if (
            data.code !== "Ok" ||
            !data.routes ||
            !data.routes.length
        ) {
            throw new Error("Маршрут не найден");
        }

        const route = data.routes[0];

        if (routeLine) {
            routeMap.removeLayer(routeLine);
        }

        routeLine = L.geoJSON(
            route.geometry,
            {
                style: {
                    color: "#B58B55",
                    weight: 5,
                    opacity: 0.85
                }
            }
        ).addTo(routeMap);

        routeMap.fitBounds(
            routeLine.getBounds(),
            { padding: [40, 40] }
        );

        const distance =
            (route.distance / 1000).toFixed(1);
            const difficulty = getRouteDifficulty(
    Number(distance),
    selectedRoutePlaces.length
);

        const hours =
            Math.floor(route.duration / 3600);

        const minutes =
            Math.round((route.duration % 3600) / 60);

        info.innerHTML = `
            <strong>Маршрут построен!</strong><br>
            Расстояние: ${distance} км<br>
            Время в пути: ${hours} ч ${minutes} мин<br>
            Количество остановок: ${selectedRoutePlaces.length}
            <br>
<strong>Сложность поездки:</strong>
<span style="color: ${difficulty.color}; font-weight: bold;">
    ${difficulty.name}
</span>
<br>
${difficulty.description}
            <p>Время расчётное и не учитывает пробки, остановки и состояние дорог.</p>
        `;

    } catch (error) {

        info.textContent =
            "Не удалось построить маршрут. Проверьте интернет и попробуйте снова.";

        console.error(error);

    }

}


