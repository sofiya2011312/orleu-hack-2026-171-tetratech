function toggleRoutePlace(place) {

    const index = selectedRoutePlaces.findIndex(
        p => p.name === place.name
    );

    if (index !== -1) {

        selectedRoutePlaces.splice(index, 1);

    } else {

        if (selectedRoutePlaces.length >= 10) {
            alert("Можно выбрать максимум 10 мест для одного маршрута.");
            return;
        }

        selectedRoutePlaces.push(place);

    }

    renderSelectedPlaces();

    renderRouteMarkers();

}


function renderSelectedPlaces() {

    const container =
        document.getElementById("selectedPlaces");

    container.innerHTML = "";

    if (selectedRoutePlaces.length === 0) {

        container.textContent =
            "Пока ничего не выбрано.";

        return;

    }

    selectedRoutePlaces.forEach((place, index) => {

        const row = document.createElement("div");

        row.className = "selected-item";

        const name = document.createElement("span");

        name.textContent =
            (index + 1) + ". " + place.name;

        const remove = document.createElement("button");

        remove.textContent = "Удалить";

        remove.addEventListener("click", () => {

            selectedRoutePlaces.splice(index, 1);

            renderSelectedPlaces();
            renderRouteMarkers();
            renderPlaces();

        });

        row.append(name, remove);

        container.appendChild(row);

    });

}


