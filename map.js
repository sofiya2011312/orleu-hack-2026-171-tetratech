async function findPlaceImage(placeName) {

    const url =
        "https://commons.wikimedia.org/w/api.php?" +
        "action=query&generator=search" +
        "&gsrsearch=" +
        encodeURIComponent(placeName + " Kazakhstan") +
        "&gsrnamespace=6&gsrlimit=5" +
        "&prop=imageinfo&iiprop=url" +
        "&iiurlwidth=1100&format=json&origin=*";

    try {

        const response = await fetch(url);

        if (!response.ok) {
            throw new Error("Ошибка поиска изображения");
        }

        const data = await response.json();

        const pages = Object.values(
            data.query?.pages || {}
        );

        const imagePage = pages.find(page =>
            page.imageinfo &&
            page.imageinfo.length > 0
        );

        if (!imagePage) return null;

        return imagePage.imageinfo[0].thumburl ||
               imagePage.imageinfo[0].url;

    } catch (error) {

        console.error("Ошибка фотографии:", error);

        return null;

    }

}


