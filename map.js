// QAZAQTRIP — CACHE FOR OSM DATA
// ============================================

const OSM_CACHE_TTL = 7 * 24 * 60 * 60 * 1000;
const OSM_REFRESH_INTERVAL = 24 * 60 * 60 * 1000;
const OSM_RETRY_INTERVAL = 15 * 60 * 1000;

function getOSMCache(key) {
    try {
        const saved = localStorage.getItem(key);
        return saved ? JSON.parse(saved) : null;
    } catch (error) {
        console.warn("Ошибка чтения кэша:", error);
        return null;
    }
}

function saveOSMCache(key, elements) {
    try {
        localStorage.setItem(key, JSON.stringify({
            savedAt: Date.now(),
            elements: elements
        }));
    } catch (error) {
        console.warn("Не удалось сохранить кэш:", error);
    }
}

async function loadOSMWithCache(key, query, endpoints, render) {

    const cached = getOSMCache(key);

    // Сначала показываем сохранённые данные
    if (cached && Array.isArray(cached.elements)) {
        render(cached.elements);

        console.log("Показаны сохранённые данные:", key);
    }

    // Если кэш свежий, не обращаемся к серверу
    if (
        cached &&
        Array.isArray(cached.elements) &&
        Date.now() - cached.savedAt < OSM_REFRESH_INTERVAL
    ) {
        return;
    }

    // Защита от частых повторных запросов
    let lastAttempt = 0;

    try {
        lastAttempt = Number(
            localStorage.getItem(key + "_lastAttempt") || 0
        );
    } catch (error) {}

    if (Date.now() - lastAttempt < OSM_RETRY_INTERVAL) {
        console.log("Повторный запрос отложен:", key);
        return;
    }

    try {
        localStorage.setItem(key + "_lastAttempt", Date.now());
    } catch (error) {}

    for (const endpoint of endpoints) {

        try {

            console.log("Обновляем данные:", endpoint);

            const response = await fetch(endpoint, {
                method: "POST",
                headers: {
                    "Content-Type":
                    "application/x-www-form-urlencoded"
                },
                body: "data=" + encodeURIComponent(query)
            });

            if (!response.ok) {
                throw new Error("HTTP " + response.status);
            }

            const data = await response.json();

            if (!Array.isArray(data.elements)) {
                throw new Error("Некорректный ответ сервера");
            }

            // Сохраняем новые данные
            saveOSMCache(key, data.elements);

            // Обновляем маркеры
            render(data.elements);

            console.log(
                "Данные успешно обновлены:",
                key,
                data.elements.length
            );

            return;

        } catch (error) {

            console.warn(
                "Сервер не ответил:",
                endpoint,
                error
            );

        }
    }

    console.warn(
        "Серверы недоступны. Оставляем сохранённые маркеры:",
        key
    );
}


