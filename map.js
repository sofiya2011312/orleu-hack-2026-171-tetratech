// ROUTE MAP MARKERS
// ============================================

function renderRouteMarkers() {

    routeMarkers.forEach(marker =>
        routeMap.removeLayer(marker)
    );

    routeMarkers = [];

    selectedRoutePlaces.forEach((place, index) => {

        const marker = L.marker([
            place.lat,
            place.lon
        ]).addTo(routeMap);

        marker.bindPopup(
            (index + 1) + ". " + escapeHTML(place.name)
        );

        routeMarkers.push(marker);

    });

    if (selectedRoutePlaces.length > 0) {

        const bounds = L.latLngBounds(
            selectedRoutePlaces.map(place => [
                place.lat,
                place.lon
            ])
        );

        routeMap.fitBounds(bounds, {
            padding: [40, 40],
            maxZoom: 12
        });

    }

}

