function renderMainMarkers() {

    mainMarkers.forEach(marker =>
        mainMap.removeLayer(marker)
    );

    mainMarkers = [];

    const area = document.getElementById("mapArea").value;

    allPlaces.forEach(place => {

        if (
            area !== "all" &&
            place.area !== area
        ) {
            return;
        }

        const attractionIcon = L.divIcon({
    className: "attraction-marker",
    html: '<div class="attraction-pin">✦</div>',
    iconSize: [38, 38],
    iconAnchor: [19, 19],
    popupAnchor: [0, -20]
});

const marker = L.marker(
    [place.lat, place.lon],
    { icon: attractionIcon }
).addTo(mainMap);

        marker.bindPopup(`
            <b>${escapeHTML(place.name)}</b>
            <br>
            ${escapeHTML(place.description)}
            <br><br>
           <button onclick="addPlaceByName('${encodeURIComponent(place.name)}')">
    Добавить в маршрут
</button>

<br><br>

<button onclick="openPlaceDetails('${encodeURIComponent(place.name)}')">
    Подробнее о месте →
</button>

        `);

        mainMarkers.push(marker);

    });

}


window.addPlaceByName = function(encodedName) {

    const name = decodeURIComponent(encodedName);

    const place = allPlaces.find(p => p.name === name);

    if (place) {
        toggleRoutePlace(place);
    }

};


