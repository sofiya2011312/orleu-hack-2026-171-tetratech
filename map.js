function detectCategory(tags) {

    if (
        tags.waterway === "waterfall" ||
        tags.natural === "water" ||
        tags.natural === "lake"
    ) {
        return "water";
    }

    if (
        tags.historic ||
        tags.heritage ||
        tags.archaeological_site
    ) {
        return "historic";
    }

    if (
        tags.natural === "peak" ||
        tags.natural === "mountain" ||
        tags.natural === "valley"
    ) {
        return "mountain";
    }

    if (
        tags.tourism ||
        tags.leisure === "park"
    ) {
        return "tourism";
    }

    return "nature";
}


